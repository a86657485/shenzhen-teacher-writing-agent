export function buildUserPrompt(topic: string, profile: WriterProfile, contexts: SearchResult[]) {
  const contextText = contexts.length
    ? contexts
        .map((item, index) => {
          const source = item.sourceUrl ? `${item.title} ${item.sourceUrl}` : item.title;
          return `资料${index + 1}｜相似度${item.score.toFixed(3)}｜${source}\n${item.content}`;
        })
        .join("\n\n---\n\n")
    : "本次未检索到高相关知识库片段。请只使用通用教育写作框架，不要编造来源。";

  return `
请根据以下用户题目生成深圳教师招聘主观题作文。

【用户题目】
${topic}

【教师身份设置】
默认角色：${profile.role}
学段：${profile.stage}
学科：${profile.subject}
目标字数：${profile.wordCount}
输出模式：${profile.outputMode}

【可参考的知识库片段】
${contextText}

【生成要求】
1. 严格按默认输出格式回答。
2. 范文部分按目标字数生成，语言要像教师招聘高分作文。
3. 结合知识库资料，但不要机械照搬原句。
4. 如果资料与题目相关性不足，请说明“本题主要调用通用框架，资料仅作风格参考”。
5. 教师身份要落地到${profile.stage}${profile.subject}课堂或课程实践。
`.trim();
}
